  String translate(String key) {
    final langTranslations = _translations[locale.languageCode];
    if (langTranslations == null) return key;
    return langTranslations[key] ?? _translations['en']![key] ?? key;
  }

  String translateWithArgs(String key, Map<String, dynamic> args) {
    String value = translate(key);
    args.forEach((argKey, argValue) {
      value = value.replaceAll('{$argKey}', argValue.toString());
    });
    return value;
  }
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) {
    return ['en', 'ar', 'ur', 'id', 'de'].contains(locale.languageCode);
  }

  @override
  Future<AppLocalizations> load(Locale locale) async {
    return AppLocalizations(locale);
  }

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}
