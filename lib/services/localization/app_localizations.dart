      'findingDetail':
          'Basierend auf Ihren letzten {cycles} aufgezeichneten Zyklen',
      'regularityHigh': 'Sehr regelmäßig',
      'regularityModerate': 'Ziemlich regelmäßig',
      'regularityLow': 'Unregelmäßig',
      'regular': 'Regelmäßig',
    },
  };

  String translate(String key) {
    final langTranslations = _translations[locale.languageCode];
    if (langTranslations == null) return key;
    return langTranslations[key] ?? _translations['en']![key] ?? key;
  }

  /// Whether [key] has its own entry for this locale, ignoring the English
  /// fallback.
  ///
  /// Prefer [resolves] when checking that the UI can render a string. Presence
  /// and value have to be distinguished because several English entries are
  /// identity translations such as `'Day': 'Day'`, where the value and the key
  /// are the same string.
  bool has(String key) =>
      _translations[locale.languageCode]?.containsKey(key) ?? false;

  /// Whether [key] can be rendered for this locale, either from its own map or
  /// from the English fallback. A false result means the raw key reaches the
  /// screen.
  bool resolves(String key) =>
      has(key) || (_translations['en']?.containsKey(key) ?? false);

  String translateWithArgs(String key, Map<String, dynamic> args) {
    String value = translate(key);
    args.forEach((argKey, argValue) {
      value = value.replaceAll('{$argKey}', argValue.toString());
    });
    return value;
  }
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) {
    return ['en', 'ar', 'ur', 'id', 'de'].contains(locale.languageCode);
  }

  @override
  Future<AppLocalizations> load(Locale locale) async {
    return AppLocalizations(locale);
  }

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}
